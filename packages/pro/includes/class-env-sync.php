<?php
/**
 * One-way environment secret import (Pro).
 *
 * @package CredentialVaultPro
 */

declare( strict_types=1 );

namespace CredentialVaultPro;

use CredentialVault\Credential_Meta;
use CredentialVault\Secrets_Bridge;
use WP_Error;

/**
 * Pull secrets from .env (WP-CLI) or HTTP vault APIs — read-only, never logged.
 */
final class Env_Sync {

	public static function register(): void {
		if ( defined( 'WP_CLI' ) && WP_CLI ) {
			\WP_CLI::add_command( 'credvault pro env-sync', array( self::class, 'cli_env_sync' ) );
			\WP_CLI::add_command( 'credvault pro env-example', array( self::class, 'cli_env_example' ) );
		}

		add_action( 'admin_post_credential_vault_pro_save_env_sync', array( self::class, 'handle_save_settings' ) );
	}

	/**
	 * @param list<string>           $args
	 * @param array<string, mixed> $assoc_args
	 */
	/**
	 * Write .env.example placeholders from the env map (no secret values).
	 *
	 * ## OPTIONS
	 *
	 * [--file=<path>]
	 * : Output path (default: ABSPATH/.env.example)
	 */
	public static function cli_env_example( array $args, array $assoc_args ): void {
		unset( $args );
		$path = isset( $assoc_args['file'] ) ? (string) $assoc_args['file'] : ABSPATH . '.env.example';
		$map  = self::mapping();

		$lines = array(
			'# Generated by Credential Vault — placeholder keys only.',
		);

		foreach ( $map as $env_key => $slug ) {
			$lines[] = $env_key . '=changeme_' . $slug;
		}

		$written = file_put_contents( $path, implode( PHP_EOL, $lines ) . PHP_EOL );
		if ( false === $written ) {
			\WP_CLI::error( 'Could not write env example file.' );
		}

		\WP_CLI::success( 'Wrote ' . $path );
	}

	public static function cli_env_sync( array $args, array $assoc_args ): void {
		unset( $args );
		$path = isset( $assoc_args['file'] ) ? (string) $assoc_args['file'] : ABSPATH . '.env';
		$dry  = isset( $assoc_args['dry-run'] );

		$map = self::mapping();
		$parsed = self::parse_dotenv( $path );

		foreach ( $map as $env_key => $slug ) {
			if ( ! isset( $parsed[ $env_key ] ) || '' === $parsed[ $env_key ] ) {
				continue;
			}

			if ( $dry ) {
				\WP_CLI::log( "Would sync {$env_key} → {$slug}" );
				continue;
			}

			$value = $parsed[ $env_key ];
			$name  = Secrets_Bridge::secret_name( $slug );
			$result = Secrets_Bridge::set_secret( $name, $value, false );
			Secrets_Bridge::memzero( $value );

			if ( is_wp_error( $result ) ) {
				\WP_CLI::warning( $result->get_error_message() );
				continue;
			}

			Credential_Meta::save( $name, $slug, 'custom', Secrets_Bridge::masked_preview( $parsed[ $env_key ] ) );
			\WP_CLI::success( "Synced {$slug}" );
		}
	}

	/**
	 * @return array<string, string> ENV_KEY => vault slug
	 */
	public static function mapping(): array {
		$stored = get_option( 'credential_vault_pro_env_map', array() );

		return is_array( $stored ) ? $stored : array();
	}

	/**
	 * @return array<string, string>
	 */
	public static function parse_dotenv( string $path ): array {
		if ( ! is_readable( $path ) ) {
			return array();
		}

		$lines = file( $path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES );
		if ( ! is_array( $lines ) ) {
			return array();
		}

		$out = array();
		foreach ( $lines as $line ) {
			$line = trim( (string) $line );
			if ( '' === $line || '#' === $line[0] ) {
				continue;
			}
			if ( false === strpos( $line, '=' ) ) {
				continue;
			}
			list( $key, $value ) = array_map( 'trim', explode( '=', $line, 2 ) );
			$value = trim( $value, "\"'" );
			$out[ $key ] = $value;
		}

		return $out;
	}

	/**
	 * Read-only pull from Doppler / 1Password / generic vault HTTP API.
	 *
	 * @return true|WP_Error
	 */
	public static function pull_http_vault( string $provider ) {
		$settings = get_option( 'credential_vault_pro_vault_http', array() );
		if ( ! is_array( $settings ) ) {
			return new WP_Error( 'config', __( 'HTTP vault settings are missing.', 'credential-vault-pro' ) );
		}

		$url   = esc_url_raw( (string) ( $settings['url'] ?? '' ) );
		$token = (string) ( $settings['token'] ?? '' );

		if ( '' === $url || '' === $token ) {
			return new WP_Error( 'config', __( 'Vault URL and token are required.', 'credential-vault-pro' ) );
		}

		$response = wp_remote_get(
			$url,
			array(
				'timeout' => 15,
				'headers' => array(
					'Authorization' => 'Bearer ' . $token,
					'Accept'        => 'application/json',
				),
			)
		);

		if ( is_wp_error( $response ) ) {
			return $response;
		}

		$code = (int) wp_remote_retrieve_response_code( $response );
		if ( $code < 200 || $code >= 300 ) {
			return new WP_Error( 'http', __( 'Vault HTTP request failed.', 'credential-vault-pro' ) );
		}

		$data = json_decode( (string) wp_remote_retrieve_body( $response ), true );
		if ( ! is_array( $data ) ) {
			return new WP_Error( 'parse', __( 'Vault response was not JSON.', 'credential-vault-pro' ) );
		}

		/**
		 * Map remote vault payload to local slugs.
		 *
		 * @param array<string, string> $map     Default empty.
		 * @param array<string, mixed>  $data    Remote JSON.
		 * @param string                $provider doppler|onepassword|generic
		 */
		$map = apply_filters( 'credential_vault_pro_vault_http_map', self::mapping(), $data, $provider );

		foreach ( $map as $remote_key => $slug ) {
			if ( ! isset( $data[ $remote_key ] ) || ! is_string( $data[ $remote_key ] ) ) {
				continue;
			}

			$value  = $data[ $remote_key ];
			$name   = Secrets_Bridge::secret_name( sanitize_key( $slug ) );
			$result = Secrets_Bridge::set_secret( $name, $value, false );
			Secrets_Bridge::memzero( $value );

			if ( is_wp_error( $result ) ) {
				return $result;
			}
		}

		return true;
	}

	public static function handle_save_settings(): void {
		if ( ! Secrets_Bridge::current_user_can_manage() ) {
			wp_die( esc_html__( 'You do not have permission to manage credentials.', 'credential-vault-pro' ) );
		}

		check_admin_referer( 'credential_vault_pro_save_env_sync' );

		$map_raw = isset( $_POST['env_map'] ) ? sanitize_textarea_field( (string) wp_unslash( $_POST['env_map'] ) ) : '';
		$map     = array();

		foreach ( preg_split( '/\r\n|\r|\n/', $map_raw ) as $line ) {
			$line = trim( $line );
			if ( '' === $line || false === strpos( $line, '=' ) ) {
				continue;
			}
			list( $env, $slug ) = array_map( 'trim', explode( '=', $line, 2 ) );
			$map[ $env ] = sanitize_key( $slug );
		}

		update_option( 'credential_vault_pro_env_map', $map, false );

		update_option(
			'credential_vault_pro_vault_http',
			array(
				'url'   => esc_url_raw( (string) ( $_POST['vault_http_url'] ?? '' ) ),
				'token' => sanitize_text_field( (string) wp_unslash( $_POST['vault_http_token'] ?? '' ) ),
			),
			false
		);

		wp_safe_redirect(
			add_query_arg(
				array(
					'page'         => 'credential-vault',
					'tab'          => 'automation',
					'vault_notice' => 'env_sync_saved',
				),
				admin_url( 'admin.php' )
			)
		);
		exit;
	}
}
